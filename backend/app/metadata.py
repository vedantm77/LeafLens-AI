def get_class_info(raw_label: str) -> Dict[str, Any]:
    """Retrieve structured metadata for a raw model class label."""
    if raw_label in DISEASE_METADATA:
        info = DISEASE_METADATA[raw_label]
        return {
            "raw_label": raw_label,
            **info
        }
    
    # Fallback parser if unknown class
    parts = raw_label.split("___")
    crop = parts[0].replace("_", " ").replace(",", "")
    disease = parts[1].replace("_", " ") if len(parts) > 1 else "Unknown"
    is_healthy = "healthy" in disease.lower()
    return {
        "raw_label": raw_label,
        "crop": crop.title(),
        "disease": disease.title(),
        "is_healthy": is_healthy,
        "severity": "none" if is_healthy else "moderate",
        "description": f"Condition observed on {crop}: {disease}.",
        "treatment": "Consult local agricultural extension service for tailored diagnosis and recommendations.",
        "prevention": ["Practice crop rotation", "Maintain proper sanitation", "Scout plants regularly"],
    }
